"""Download the site's web fonts from Google Fonts and self-host them.

    python scripts/fetch_fonts.py

Reads the "fonts" list in content/site.json, e.g.
    "fonts": [{"family": "Source Serif 4", "axes": "ital,opsz,wght@0,8..60,400..600;1,8..60,400"}]
and writes Latin-subset woff2 files to assets/fonts/ plus assets/css/fonts.css.
Run it once after changing fonts; the files are committed with the site, so
visitors never touch a third-party server.
"""
import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS_DIR = ROOT / "assets" / "fonts"
CSS_OUT = ROOT / "assets" / "css" / "fonts.css"
# A modern UA so Google serves woff2.
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def main() -> None:
    site = json.loads((ROOT / "content" / "site.json").read_text(encoding="utf-8"))
    fonts = site.get("fonts", [])
    if not fonts:
        raise SystemExit('No "fonts" list in content/site.json')
    FONTS_DIR.mkdir(parents=True, exist_ok=True)
    for old in FONTS_DIR.glob("*.woff2"):
        old.unlink()

    out = ["/* Generated by scripts/fetch_fonts.py, do not edit. */"]
    saved = {}  # url -> filename; variable fonts serve one file for several weights
    for f in fonts:
        family = f["family"]
        spec = family.replace(" ", "+") + (f":{f['axes']}" if f.get("axes") else "")
        css = fetch(f"https://fonts.googleapis.com/css2?family={spec}&display=swap").decode()
        # Keep only the latin subset blocks (preceded by a /* latin */ comment).
        blocks = re.findall(r"/\* (latin(?:-ext)?) \*/\s*(@font-face\s*{[^}]+})", css)
        for subset, block in blocks:
            if subset != "latin":
                continue
            url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
            style = re.search(r"font-style:\s*(\w+)", block).group(1)
            weight = re.search(r"font-weight:\s*([\d ]+)", block).group(1).strip().replace(" ", "-")
            if url not in saved:
                saved[url] = f"{re.sub(r'[^a-z0-9]+', '-', family.lower())}-{style}-{weight}.woff2"
                (FONTS_DIR / saved[url]).write_bytes(fetch(url))
                print(f"  {saved[url]}")
            out.append(block.replace(url, f"../fonts/{saved[url]}"))
    CSS_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {CSS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
